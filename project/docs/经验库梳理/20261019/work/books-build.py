def plain(s):
    s=re.sub(r'<!--.*?-->','',s)
    s=re.sub(r'\*\*|`','',s).strip().strip('> ').strip()
    return s

def extract_summary(lines):
    # Only extract substantive source paragraphs; source/META/navigation never count as rules.
    content=[]; priorities=[]
    for raw in lines:
        s=plain(raw).lstrip('- ').strip()
        if not s or s.startswith(('#','---','<!--')):continue
        if re.match(r'^(来源|提取时间|专题|原文|适用条件|出处|文件|书籍|状态|作者|参考资料|本条来源|占类|课体|时间|关键神煞|反馈|案例佐证)[：:（(]',s):continue
        if s in ['详细说明：','判断要点：','判断思路：','课式特征：','可复用规则：','核心口诀：']:continue
        if re.match(r'^(核心内容|核心技法|经验规则|核心口诀|可复用规则)[：:]',s):
            priorities.append(re.sub(r'^[^：:]+[：:]\s*','',s))
        elif s.startswith('|'):
            if re.fullmatch(r'[| :\-]+',s):continue
            content.append(s.replace('|',' / ').strip(' /'))
        else:content.append(s.lstrip('- ').strip())
    selected=[]
    for s in priorities+content:
        if s and s not in selected:
            if sum(map(len,selected))+len(s)<=240:selected.append(s)
            elif not selected:selected.append(s)
        if sum(map(len,selected))>=190:break
    text='；'.join(selected)
    if len(text)>250:
        pieces=re.split(r'(?<=[。；;])',text)
        kept=''
        for piece in pieces:
            if len(kept)+len(piece)>245:break
            kept+=piece
        text=kept or text[:240]+'（详见原文）'
    return text or '本段为原资料的说明与导航，具体关系保留在来源范围内，不作为新的预测规则。'

def categories(title,body,path,own_meta='',parent=''):
    if any(x in path for x in ['推命','终身论命','推命参考']):return ['推命']
    pairs=[('胎产',['胎','孕','产子','子嗣']),('财运占',['求财','交易','买卖','经商','财爻']),('事业占',['官禄','仕途','升迁','仕宦','功名','前程','干贵','官职']),('学业占',['科举','考试','选举','科场','乡试','会试','院试']),('感情占',['婚','续弦']),('健康占',['疾病','占病','病症','生死','医药','寿夭']),('出行占',['出行','行人','远行','迁移','进退行','逃亡','子逃']),('失物占',['失物','盗贼','贼盗','失马','失驴','贼方']),('官讼占',['诉讼','词讼','占讼','讼事','刑狱','重罪']),('家宅占',['宅','坟','阴宅','风水','修造']),('天时占',['雨','雪','晴','天时','蝗','岁收','丰歉','田蚕','农桑']),('射覆',['射覆','袖藏','覆何'])]
    result=[c for c,ks in pairs if any(k in title for k in ks)]
    if any(x in title for x in ['身命','终身','命数']):result.append('推命')
    if any(x in title for x in ['受症','必死','手足不举','无生气']):result.append('健康占')
    # An explicit case's question outranks a symbol such as 财爻 in a disease title.
    explicit=re.search(r'占类[：:]\s*([^\n]+)',plain(body))
    if explicit:
        label=explicit.group(1)
        direct=[]
        for c,ks in pairs:
            if any(k in label for k in ks):direct.append(c)
        if '病' in label or '医' in label:direct.append('健康占')
        if '索债' in label or '经商' in label:direct.append('财运占')
        if '失' in label or '盗' in label:direct=['失物占']
        if '兵' in label or '战' in label:direct.append('杂事')
        if direct:result=direct
    # Read only the META before this section, never the next section's trailing META.
    meta_result=[]
    for label in re.findall(r'占类=([^|>]+)',own_meta):
        for c,ks in pairs:
            if any(k in label for k in ks):meta_result.append(c)
        for key,c in [('通用','通用'),('疾病','健康占'),('财运','财运占'),('事业','事业占'),('学业','学业占'),('感情','感情占'),('兵占','杂事'),('推命','推命')]:
            if key in label:meta_result.append(c)
    if meta_result:result=result+meta_result
    if not result:
        result=[c for c,ks in pairs if any(k in parent for k in ks)]
    return list(dict.fromkeys(result)) or ['通用']

TAGS=['空亡','应期','类神','取数','权重','反吟','三传','反证','旺衰','年命','行年','本命','天将','神煞','贵人','德禄','驿马','丁马','伏吟','墓库','刑冲合害','阴神','十二宫','运限','同课异断','五行','四课','发用','三合','六合','课体','生克','太岁','月建','外应','闭口','玄武','勾陈','朱雀','白虎','天罡','课命爻象','六亲','书籍溯源']
def tags_for(title,body):
    text=title+' '+body[:2000]
    result=[t for t in TAGS if t in text]
    for pattern,tag in [('空|旬空','空亡'),('数理|数法|数字|里数|多少','取数'),('旺|衰|休囚|五气','旺衰'),('年月日时|年月日|填实|待冲|归期','应期'),('干支|克日|生干|克干|递生|递克','生克'),('墓|绝','墓库'),('冲|刑|合|害','刑冲合害'),('四化|嫁接|病药|叠宫','权重')]:
        if re.search(pattern,title) and tag not in result:result.append(tag)
    return result[:12] or ['书籍溯源']

