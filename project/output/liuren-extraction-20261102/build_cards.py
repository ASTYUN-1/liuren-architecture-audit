def ev(path,a,b,role,author='未知',case_id=None,note=None):
    raw=(ROOT/path).read_bytes()
    out=dict(path=path,line_start=a,line_end=b,quote='\n'.join(raw.decode('utf-8-sig').splitlines()[a-1:b]),sha256=hashlib.sha256(raw).hexdigest(),role=role,author=author)
