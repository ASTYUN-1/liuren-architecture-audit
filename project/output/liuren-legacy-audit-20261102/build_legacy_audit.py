import json
import hashlib
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parents[2]
CATALOG = {d['id']: d for d in (json.loads(s) for s in (ROOT/'docs/经验库梳理/20261019/data/catalog.jsonl').read_text(encoding='utf-8').splitlines())}
AUDITS, RULES = [], []

def ref(p, a, b, role='旧AI归纳', author='未知'):
    raw = (ROOT/p).read_bytes()
    lines = raw.decode('utf-8-sig').splitlines()
    assert 1 <= a <= b <= len(lines), (p,a,b)
    return dict(path=p,line_start=a,line_end=b,quote='\n'.join(lines[a-1:b]),sha256=hashlib.sha256(raw).hexdigest(),role=role,author=author)

def legacy(ids):
    return [ref(CATALOG[i]['source'],CATALOG[i]['line_start'],CATALOG[i]['line_end']) for i in ids]

def add(n, ids, title, disposition, finding, reasoning, refs, rule_title, conditions, conclusion,
        exclusions, alternatives, paths=(), relations=(), origin='本轮归纳', status='candidate', limits=()):
    aid, rid = f'LA26-LEGACY-{n:03}', f'LR26-LEGACY-{n:03}'
    evidence = legacy(ids)+refs
    common_limits = ['本批已读答案与反馈，属于方法开发暴露；全部独立验证次数为0。',
                     '证据哈希绑定当前原文件；任一证据文件变化后本卡须失效并重新核对。']
    AUDITS.append(dict(schema='liuren-audit-v1',id=aid,title=title,target_entry_ids=ids,target_case_paths=list(paths),
        disposition=disposition,finding=finding,reasoning=reasoning,evidence_refs=evidence,
        replacement_rule_ids=[rid],limitations=list(limits)+common_limits,review_state='source_checked',independent_validation_count=0))
    RULES.append(dict(schema='liuren-rule-card-v1',id=rid,title=rule_title,categories=sorted(set(c for i in ids for c in CATALOG[i]['categories'])),
        claim_origin=origin,review_state='source_checked',status=status,conditions=conditions,exclusions=exclusions,
        conclusion=conclusion,reasoning_steps=reasoning,alternatives=alternatives,evidence_refs=evidence,
        support_case_ids=list(paths),counterexample_case_ids=[],legacy_entry_ids=ids,relations=list(relations),
        limitations=list(limits)+common_limits,independent_validation_count=0))

