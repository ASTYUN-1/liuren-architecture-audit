import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {registerHooks} from 'node:module';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../../',import.meta.url));
registerHooks({resolve(s,c,next){if(s==='@opencode-ai/plugin')return next(pathToFileURL(path.join(root,'.opencode/node_modules/@opencode-ai/plugin/dist/index.js')).href,c);return next(s,c);}});
const load=async p=>JSON.parse(await fs.readFile(path.join(root,p),'utf8'));
const pointer=await load('.opencode/liuren-active.json');
assert.equal(pointer.release,'20261115-class-selection-62');
const {default:plugin}=await import('../../.opencode/plugins/liuren-adjudication.ts');
const hooks=await plugin({directory:root,client:{session:{messages:async()=>({data:[]})}}});
const ctx={agent:'liuren',sessionID:'class62_interface_no_model',directory:root,abort:new AbortController().signal};
const workflow=JSON.parse(await hooks.tool.liuren_tool_help.execute({topic:'workflow',domains:['finance']},ctx));
assert.equal(workflow.execution_health.ready,true);
assert.equal(workflow.adjudication_enabled,false);
assert.equal(workflow.release,pointer.release);
const {default:materials}=await import('../../.opencode/tools/liuren_materials.ts');
const material=await materials.execute({action:'method',modules:['class-selection-trial','finance','relationship']},ctx);
assert.ok(material.output.includes('经营概况不缩成近期进项'));
assert.ok(material.output.includes('关系主线不缩成一方'));
assert.ok(material.output.includes('开店“通类虽在财，但专类却不在财”'));
assert.ok(material.output.includes('地盘本命/行年X上见Y乘Z'));
assert.ok(material.output.includes('trial-domain-finance'));
assert.ok(!material.output.includes('# 本机占事共用判断规范'));
const prior=await load('output/opencode-trial61-class-newfive-20261115-09-deepseek/execution-audit.json');
const ref=prior.cases[0].archives[0];
const chart=JSON.parse(await hooks.tool.liuren_compute.execute({action:'chart',archive:{path:ref.path,sha256:ref.sha256},symbols:['巳']},ctx));
assert.equal(chart.trial_judgment_policy.selection_policy.id,'class-selection-source-62');
assert.equal(chart.trial_judgment_policy.id,'liuren-trial-decision-61');
const cfg=await load('opencode.json');
const beforeCfg=await load('output/liuren-class-selection-62/before/opencode.json');
assert.equal(cfg.model,beforeCfg.model);
assert.equal(cfg.agent.liuren.model,beforeCfg.agent.liuren.model);
assert.equal(cfg.agent.liuren.variant,beforeCfg.agent.liuren.variant);
const before=await load('output/liuren-class-selection-62/before.json');
for(const [f,h] of Object.entries(before.frozen))assert.equal(createHash('sha256').update(await fs.readFile(path.join(root,f))).digest('hex'),h,f);
const report={release:pointer.release,workflow_ready:true,adjudication_enabled:false,actual_materials_adapter_loaded_revised_rules:true,actual_chart_query_includes_selection_policy:true,strength_policy_unchanged:true,default_model_settings_unchanged:true,frozen_61_unchanged:true,model_calls:0,predictive_improvement_tested:false};
await fs.writeFile(new URL('./acceptance.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
